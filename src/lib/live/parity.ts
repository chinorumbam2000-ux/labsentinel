/**
 * The browser/backend parity fixture for Live Surveillance.
 *
 * One function builds it from the browser implementation: every result the
 * simulated sources send (as plain fields the backend turns into FHIR
 * Observations) and every closed day's signal per live profile, as the
 * browser engine calculated it. backend/tests/test_live_parity.py ingests the
 * same results through the real FHIR pipeline, runs the backend engine per
 * profile, and checks it gets the same signals. A frontend test checks the
 * committed fixture is still what the browser produces.
 *
 * Regenerate with: npx vite-node scripts/export-live-parity.ts
 */
import { ALL_DATES } from './dataset';
import { clock, planResults } from './sources';
import { LIVE_PROFILES, LiveSimulator } from './simulator';
import { PROFILE_BY_ID } from '../profiles/registry';

export interface ParitySignal {
  date: string;
  status: string;
  tests: number;
  positives: number;
  baselineObservedDays: number;
  baselineMeanTests: number | null;
  baselinePositivity: number | null;
  affectedFacilities: string[];
  affectedAreas: string[];
  persistenceDays: number;
  components: Record<string, { normalized: number; points: number }> | null;
  composite: number | null;
  severity: string | null;
}

export interface ParityFixture {
  description: string;
  results: Array<{
    id: string;
    facility: string;
    date: string;
    collected: string;
    delivered: string;
    loinc: string;
    positive: boolean;
    specimen: boolean;
    patient: string;
  }>;
  /** Per profile engine key (the backend's storage key), per date. */
  signals: Record<string, ParitySignal[]>;
}

const round = (value: number | null, places = 6) =>
  value === null ? null : Math.round(value * 10 ** places) / 10 ** places;

export const buildParityFixture = (): ParityFixture => {
  const sim = new LiveSimulator();
  while (!sim.finished) sim.advance(10_000);
  return {
    description:
      'Signal by ProbeSyQ Live Surveillance parity fixture: synthetic results from the three simulated sources and the browser engine\'s closed-day signals. Generated by scripts/export-live-parity.ts; do not edit by hand.',
    results: planResults().map((r) => ({
      id: r.id,
      facility: r.hospitalId,
      date: r.date,
      collected: clock(r.collectedMinute),
      delivered: clock(r.deliveredMinute),
      loinc: r.code,
      positive: r.positive,
      specimen: r.withSpecimen,
      patient: r.patientRef,
    })),
    signals: Object.fromEntries(
      LIVE_PROFILES.map((id) => [
        PROFILE_BY_ID[id].engineKey!,
        Object.values(sim.closed[id])
          .sort((a, b) => a.day - b.day)
          .map((s) => ({
            date: ALL_DATES[s.day - 1],
            status: s.status,
            tests: s.current.tests,
            positives: s.current.positive,
            baselineObservedDays: s.baseline.observedDays,
            baselineMeanTests: round(s.baseline.meanTests),
            baselinePositivity: round(s.baseline.positivity),
            affectedFacilities: s.affected,
            affectedAreas: s.affectedAreas,
            persistenceDays: s.persistenceDays,
            components: s.score
              ? Object.fromEntries(s.score.components.map((c) => [c.key, { normalized: round(c.score)!, points: c.points }]))
              : null,
            composite: s.score?.composite ?? null,
            severity: s.score?.severity ?? null,
          })),
      ]),
    ),
  };
};
