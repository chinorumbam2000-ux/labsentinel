"""
``python -m app.demo.evaluation_summary``: write docs/evaluation-summary.md,
the presentation-ready summary of the Phase 10 evaluation.

It only READS the committed artifact (backend/evaluation-results/
evaluation-summary.json): nothing is re-run, recalculated or typed by hand, so
the summary can never disagree with the evaluated results. The tradeoff
wording names no winner.

    python -m app.demo.evaluation_summary           write the document
    python -m app.demo.evaluation_summary --check   exit 1 if it is out of date
"""

import json
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[2]
ARTIFACT = BACKEND_DIR / "evaluation-results" / "evaluation-summary.json"
DOCUMENT = BACKEND_DIR.parent / "docs" / "evaluation-summary.md"
DETECTORS = ("composite", "ewma", "cusum")
NAME = {"composite": "Composite", "ewma": "EWMA", "cusum": "CUSUM"}


def _num(value, digits: int = 2) -> str:
    if value is None:
        return "—"
    if float(value).is_integer():
        return str(int(value))
    return f"{value:.{digits}f}".rstrip("0").rstrip(".")


def _pct(p: dict) -> str:
    if p["value"] is None:
        return "—"
    low, high = p["ci95"]
    return f"{p['numerator']}/{p['denominator']} = {100 * p['value']:.1f} % ({100 * low:.1f}–{100 * high:.1f})"


def _count(p: dict) -> str:
    return f"{p['numerator']}/{p['denominator']}"


def _delay(d: dict) -> str:
    return "—" if not d["n"] else f"{_num(d['median'])} ({_num(d['p25'])}–{_num(d['p75'])})"


def render(summary: dict) -> str:
    overall = summary["overall"]["detectors"]
    scenarios = {s["id"]: s for s in summary["scenarios"]}
    burden = {d: overall[d]["burden"]["false_alert_days_per_100_normal_days"] for d in DETECTORS}
    highest = max(DETECTORS, key=lambda d: burden[d])
    lowest = min(DETECTORS, key=lambda d: burden[d])
    gradual, volume, local = scenarios["S03-gradual"], scenarios["S05-volume-only"], scenarios["S06-single-facility"]

    def det(s: dict, d: str) -> dict:
        return s["detectors"][d]

    lines = [
        "# LabSentinel capstone evaluation — summary",
        "",
        f"> **{summary['disclaimer']}**",
        "",
        "Generated by `python -m app.demo.evaluation_summary` from the committed Phase 10 artifact",
        "(`backend/evaluation-results/evaluation-summary.json`); no number here was recalculated or typed by hand.",
        "Full report: [evaluation-report.md](../backend/evaluation-results/evaluation-report.md).",
        "",
        "## Design in one paragraph",
        "",
        "The Composite Outbreak Signal Score, EWMA and CUSUM ran unchanged, with their application defaults,",
        f"on {len(summary['scenarios'])} synthetic scenarios with known ground truth, {summary['repetitions']} seeded runs each",
        f"(seed {summary['seed']}). Every outbreak starts on {summary['calendar']['onset']}. {summary['overall']['scope']}",
        "Detection: Composite at High or Critical; EWMA at STATISTICAL ALERT; CUSUM when either metric reaches h.",
        "",
        "## Pooled results",
        "",
        "| Metric | " + " | ".join(NAME[d] for d in DETECTORS) + " |",
        "|---|" + "---|" * len(DETECTORS),
    ]
    rows = [
        ("Outbreak runs detected (sensitivity)", lambda m: _pct(m["realization_level"]["sensitivity"])),
        ("No-outbreak runs without any alert (specificity)", lambda m: _pct(m["realization_level"]["specificity"])),
        ("PPV, runs (design-dependent)", lambda m: _pct(m["realization_level"]["precision"])),
        ("NPV, runs (design-dependent)", lambda m: _pct(m["realization_level"]["npv"])),
        ("Outbreak days in alert", lambda m: _pct(m["day_level"]["sensitivity"])),
        ("Normal days not in alert", lambda m: _pct(m["day_level"]["specificity"])),
        ("Median detection delay (IQR), days", lambda m: _delay(m["detection_delay_days"])),
        ("False-alert days per 100 normal days", lambda m: _num(m["burden"]["false_alert_days_per_100_normal_days"], 3)),
        ("State changes per 100 normal days", lambda m: _num(m["stability"]["transitions_per_100_normal_days"], 3)),
    ]
    for label, get in rows:
        lines.append(f"| {label} | " + " | ".join(get(overall[d]) for d in DETECTORS) + " |")

    lines += [
        "",
        "Values in brackets are Wilson 95 % intervals.",
        "",
        "## Tradeoffs (no method is declared best)",
        "",
        f"- **Composite** — more conservative: the {'lowest' if lowest == 'composite' else 'a low'} false-alert burden "
        f"({_num(burden['composite'])} per 100 normal days). Slower and less sensitive in some scenarios: detected "
        f"{_count(det(gradual, 'composite')['realization_level']['sensitivity'])} slow gradual and "
        f"{_count(det(local, 'composite')['realization_level']['sensitivity'])} single-facility outbreaks.",
        f"- **EWMA** — more sensitive ({_count(overall['ewma']['realization_level']['sensitivity'])} outbreak runs) and "
        f"earlier in some gradual scenarios (slow gradual median {_num(det(gradual, 'ewma')['detection_delay_days']['median'])} "
        f"vs {_num(det(gradual, 'composite')['detection_delay_days']['median'])} days). Higher false-alert burden "
        f"({_num(burden['ewma'])} per 100 normal days), including "
        f"{_count(det(volume, 'ewma')['realization_level']['false_positive_rate'])} volume-only surges.",
        f"- **CUSUM** — sensitivity similar to EWMA ({_count(overall['cusum']['realization_level']['sensitivity'])} outbreak "
        f"runs, median delay {_num(overall['cusum']['detection_delay_days']['median'])} days), responsive to sustained shifts; "
        f"{'the highest' if highest == 'cusum' else 'a high'} false-alert burden here ({_num(burden['cusum'])} per 100 normal days).",
        "",
        "## By scenario",
        "",
        "Outbreak scenarios: runs detected and median delay (days). No-outbreak scenarios: runs with a false alert.",
        "",
        "| Scenario | Ground truth | " + " | ".join(NAME[d] for d in DETECTORS) + " |",
        "|---|---|" + "---|" * len(DETECTORS),
    ]
    for s in summary["scenarios"]:
        cells = []
        for d in DETECTORS:
            m = det(s, d)
            if s["ground_truth"]["outbreak_present"]:
                cells.append(f"{_count(m['realization_level']['sensitivity'])}, {_num(m['detection_delay_days']['median'])}")
            else:
                cells.append(f"{_count(m['realization_level']['false_positive_rate'])} false")
        truth = "outbreak" if s["ground_truth"]["outbreak_present"] else "no outbreak"
        lines.append(f"| {s['name']} | {truth} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## What this does and does not show",
        "",
        "- It shows how the three prototype methods behave, relative to each other, on designed synthetic data.",
        "- It does not establish clinical or epidemiological validity, real-world PPV, or performance on real outbreaks.",
        "- Weaknesses it found are documented as future work, not tuned away: see `/architecture` and",
        "  [backend/README.md](../backend/README.md#weaknesses-found-recommendations-not-redesigns).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render(json.loads(ARTIFACT.read_text(encoding="utf-8")))
    if "--check" in argv:
        current = DOCUMENT.read_text(encoding="utf-8").replace("\r\n", "\n") if DOCUMENT.exists() else ""
        if current != text:
            print(f"{DOCUMENT} is out of date: run python -m app.demo.evaluation_summary")
            return 1
        print(f"{DOCUMENT.name} matches the committed evaluation artifact.")
        return 0
    DOCUMENT.parent.mkdir(parents=True, exist_ok=True)
    DOCUMENT.write_text(text, encoding="utf-8")
    print(f"Wrote {DOCUMENT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
